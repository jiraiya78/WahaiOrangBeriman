/**
 * Merge ayat-base.json + meta-batch-*.json into js/data/ayat.js
 * - Strips leading Bismillah if present
 * - Drops 33:56 (vocative is mid-verse, not verse-initial)
 */

import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const dataDir = path.join(__dirname, "..", "js", "data");

const base = JSON.parse(fs.readFileSync(path.join(dataDir, "ayat-base.json"), "utf8"));
const batches = [1, 2, 3, 4].map((n) => {
  const p = path.join(dataDir, `meta-batch-${n}.json`);
  if (!fs.existsSync(p)) throw new Error(`Missing ${p}`);
  return JSON.parse(fs.readFileSync(p, "utf8"));
});

const meta = Object.assign({}, ...batches);

function cleanEn(text) {
  return String(text)
    .replace(/\[[^\]]*\]/g, "")
    .replace(/\s{2,}/g, " ")
    .replace(/\s+([.,;:!?])/g, "$1")
    .trim();
}

function stripLeadingBismillah(arabic) {
  // Uthmani vocative opens with يَٰٓ — strip anything before first occurrence
  const ya = arabic.indexOf("يَٰٓ");
  if (ya > 0) return arabic.slice(ya).trim();
  return arabic;
}

const SKIP = new Set(["33-56"]);

const ayat = base.ayat
  .filter((a) => !SKIP.has(a.id))
  .map((a) => {
    const m = meta[a.id];
    if (!m || !m.guidance || !m.tafsir) {
      throw new Error(`Missing meta for ${a.id}`);
    }
    return {
      id: a.id,
      surah: a.surah,
      surahName: a.surahName,
      ayah: a.ayah,
      arabic: stripLeadingBismillah(a.arabic),
      translation: {
        bm: a.translation.bm.trim(),
        en: cleanEn(a.translation.en)
      },
      guidance: {
        bm: m.guidance.bm.trim(),
        en: m.guidance.en.trim()
      },
      tafsir: {
        bm: m.tafsir.bm.trim(),
        en: m.tafsir.en.trim()
      }
    };
  });

const stillPrefixed = ayat.filter((a) => a.arabic.startsWith("بِسْمِ"));
if (stillPrefixed.length) {
  console.warn(
    "Still have Bismillah prefix:",
    stillPrefixed.map((a) => a.id + " => " + a.arabic.slice(0, 50))
  );
}

const header = `/**
 * Ayat yang bermula dengan يَا أَيُّهَا الَّذِينَ آمَنُوا
 * Jumlah: ${ayat.length} (33:56 dikecualikan — seruan di tengah ayat).
 * Terjemahan: BM (Abdullah Muhammad Basmeih) + English (Saheeh International).
 * Tafsir: ringkasan gaya Ibn Kathir (BM + EN).
 * Guidance: ringkas 1–2 ayat panduan (BM + EN).
 * Generated by scripts/build-ayat-js.mjs
 */

const APP_AYAT = `;

const outPath = path.join(dataDir, "ayat.js");
fs.writeFileSync(outPath, header + JSON.stringify(ayat, null, 2) + ";\n", "utf8");
console.log(`Wrote ${ayat.length} ayat -> ${outPath}`);
console.log("Sample 5-1 start:", ayat.find((a) => a.id === "5-1")?.arabic.slice(0, 40));
console.log("Has 33-56?", ayat.some((a) => a.id === "33-56"));
